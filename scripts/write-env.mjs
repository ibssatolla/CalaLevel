// Writes js/env.js from .env (or from the environment). The app has no build step, so this is the "env" mechanism.
// Usage: node scripts/write-env.mjs
// Only the two public variables are written. If a service-role key is detected anywhere in the input, the script stops.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const env = { ...process.env };
const file = path.join(root, '.env');
if (existsSync(file)) {
    for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
        const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
        if (m && !line.trim().startsWith('#')) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
    }
}
const url = env.VITE_SUPABASE_URL || '';
const key = env.VITE_SUPABASE_ANON_KEY || '';

function claims(jwt) {
    try { return JSON.parse(Buffer.from(jwt.split('.')[1], 'base64url').toString()); } catch { return null; }
}
if (/service_role/i.test(key) || claims(key)?.role === 'service_role' || /^sb_secret_/.test(key)) {
    console.error('Stop: VITE_SUPABASE_ANON_KEY holds a SECRET (service-role) key. Use the public anon or publishable key.');
    process.exit(1);
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)$/.test(url) && !/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(url)) {
    console.error(`Stop: VITE_SUPABASE_URL looks wrong: "${url}". Expected https://<project-ref>.supabase.co`);
    process.exit(1);
}
if (!key) { console.error('Stop: VITE_SUPABASE_ANON_KEY is empty.'); process.exit(1); }

writeFileSync(path.join(root, 'js', 'env.js'), `// Generated by scripts/write-env.mjs. Public values only. Do not put secrets here.
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(key)};
`);
console.log('Wrote js/env.js');
