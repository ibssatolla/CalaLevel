import { createClient } from '@supabase/supabase-js';
import { startLocalSupabase } from './local-supabase.mjs';
const sb = await startLocalSupabase({ dbName: 'cala_smoke' });
const mem = {}; const storage = { getItem: k => mem[k] ?? null, setItem: (k, v) => { mem[k] = v; }, removeItem: k => { delete mem[k]; } };
const c = createClient(sb.url, sb.anonKey, { auth: { storage, flowType: 'pkce', persistSession: true, autoRefreshToken: false, detectSessionInUrl: false } });
const su = await c.auth.signUp({ email: 'n@example.com', password: 'Passw0rd!', options: { data: { accepted_terms: '2026-11-13', accepted_privacy: '2026-11-13' }, emailRedirectTo: 'http://localhost/app' } });
console.log('signup', su.error?.message, !!su.data.user, su.data.session);
let li = await c.auth.signInWithPassword({ email: 'n@example.com', password: 'Passw0rd!' });
console.log('login before confirm:', li.error?.code);
const link = await sb.followEmailLink('n@example.com');
const r = await fetch(link, { redirect: 'manual' }); const loc = r.headers.get('location'); console.log('verify ->', r.status, loc);
const code = new URL(loc).searchParams.get('code');
const ex = await c.auth.exchangeCodeForSession(code);
console.log('exchange', ex.error?.message, ex.data.session?.user.email);
const g = await c.rpc('get_progress'); console.log('progress', g.error?.message, g.data?.profile);
const bad = await c.rpc('record_workout', { p_client_id: 'x', p_type: 'push', p_title: 't', p_exercises: [], p_duration: 1 }); console.log('workout before onboarding:', bad.error?.message);
const direct = await c.from('characters').update({ total_xp: 9999 }).eq('user_id', su.data.user.id); console.log('direct update:', direct.error?.code, direct.error?.message);
const anon = createClient(sb.url, sb.anonKey, { auth: { storage: { getItem: () => null, setItem() {}, removeItem() {} }, persistSession: false } });
console.log('anon rpc:', (await anon.rpc('get_progress')).error?.message);
await sb.close(); process.exit(0);
